"""Write factory-default settings to an Alinco DR-138 MKII over its ERW-7 clone cable.

WARNING: THIS ERASES EVERY EXISTING CHANNEL/SETTING ON THE RADIO, NOT JUST CHANNEL 0. It writes
the complete factory-default image every run, with your EDITABLE FIELDS overrides patched onto
channel 0 only. If the radio already has channels 1-199, DTMF codes, etc. programmed, they are
gone after this runs -- this is a factory reset with one customized channel, not a selective patch.

This is a worked EXAMPLE, meant to be copied and edited, not run unmodified against a radio you
care about. It does two things at once:
  1. Demonstrates the full read/write wire protocol for this radio (run with --write to use it).
  2. Ships the complete factory-default 16KB memory image inline (FACTORY_IMAGE_HEXDUMP below) so
     the whole thing is self-contained -- no external .bin file needed at runtime.

Everything you'd actually want to change (channel frequency, name, CTCSS, etc.) is collected in
the EDITABLE FIELDS block near the top. Edit those, leave everything else alone, and this script
writes your values on top of the factory-default image instead of a pure factory reset.

Full byte-level reference, including every offset touched below: ../alinco-dr138-mkii_protocol.md
Narrative / safety notes for this radio: ../alinco-dr138-mkii_readme.md

SAFETY
------
- Writing bad data to unmapped ("unknown") regions can brick the radio or corrupt calibration data.
  This script only ever touches offsets protocol.md marks "confirmed".
- --write refuses to run without --backup PATH (reads the radio and saves it first) unless you
  pass --skip-backup explicitly. Test on a radio you can afford to get wrong regardless.
- --write aborts if the radio's ID reply doesn't contain "DJ-138" (this radio's model string) --
  this script's offsets and frame shapes are NOT verified for any other Alinco model. Pass --force
  to override, at your own risk.
- Frequency/power/duplex fields can put a radio outside its type-approved parameters or outside
  what your license/region permits -- check that yourself, this script doesn't.
- The 5-Tone used-flag bitmap (0x0390) and Encode memory row 0 (0x0d00) are DISPUTED -- two
  independently-verified captures disagree on what "factory default" actually is there. This
  script ships the raw captured value as-is; see protocol.md before relying on that one region.
"""

