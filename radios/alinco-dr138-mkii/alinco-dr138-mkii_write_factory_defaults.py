def _parse_hexdump(text: str) -> bytearray:
    image = bytearray()
    for line in text.strip().splitlines():
        line = line.split("#", 1)[0].strip()  # drop the trailing comment, if any
        if not line:
            continue
        addr_str, hex_str = line.split(":", 1)
        addr = int(addr_str, 16)
        chunk = bytes.fromhex(hex_str.strip())
        offset = addr - FACTORY_IMAGE_BASE
        image[offset:offset + len(chunk)] = chunk
    return image


def build_factory_image() -> bytearray:
    """The base 16128-byte image (0x0100-0x3ff0) before any EDITABLE FIELDS overrides."""
    return _parse_hexdump(FACTORY_IMAGE_HEXDUMP)


def apply_overrides(image: bytearray, overrides: dict) -> None:
    """Patch {absolute_offset: bytes} entries onto image in place."""
    for addr, value in overrides.items():
        offset = addr - FACTORY_IMAGE_BASE
        image[offset:offset + len(value)] = value


# ════════════════════════════════════════════════════════════════════════════
# Wire protocol -- see protocol.md's "Wire frames" table for the byte-exact
# reference this implements. MKII-specific: write frames carry a trailing
# 0x06 that read frames don't; do not assume this shape for other Alinco
# models (the DR-138T's write frame is 21 bytes, one byte shorter).
# ════════════════════════════════════════════════════════════════════════════
_SERIAL_BAUD = 9600
_SERIAL_TIMEOUT = 10.0  # seconds
_HANDSHAKE = b"PROGRAM"
_HANDSHAKE_READY = bytes([0x51, 0x58, 0x06])
_READ_CMD = 0x52
_WRITE_CMD = 0x57
_ACK = 0x06
_END_CMD = b"END"
_BLOCK_LEN = 0x10
_MANDATORY_PROBE_ADDR = 0x0040  # first command after ID/version, every session, or the radio
                                 # never auto-resets after a write (see protocol.md)
_WRITE_START = 0x0100
_WRITE_END = 0x3ff0  # inclusive
_EXPECTED_MODEL = "DJ-138"  # what this radio's ID reply should contain; abort if it doesn't


def _read_exact(ser: "serial.Serial", n: int, what: str) -> bytes:
    data = ser.read(n)
    if len(data) != n:
        raise IOError(
            f"Timed out reading {what} (got {len(data)} of {n} bytes). Check the cable, and "
            "confirm the radio is in RS-232C clone mode with a matching baud rate."
        )
    return data


def _expect(ser: "serial.Serial", expected: bytes, what: str) -> None:
    got = _read_exact(ser, len(expected), what)
    if got != expected:
        raise IOError(f"Unexpected reply for {what}: expected {expected!r}, got {got!r}")


def handshake(ser: "serial.Serial") -> str:
    ser.write(_HANDSHAKE)
    ser.flush()
    _expect(ser, _HANDSHAKE, "handshake echo")
    _expect(ser, _HANDSHAKE_READY, "handshake ready bytes")

    ser.write(bytes([0x02]))
    ser.flush()
    id_reply = _read_exact(ser, 9, "ID reply")  # 0x02 + model[7] + 0x00
    _read_exact(ser, 7, "version reply")  # 0x05 + "V100" + 0xe0 0x00
    model = id_reply[1:8].decode("ascii", errors="replace").rstrip("\x00")

    # Mandatory probe -- must happen before any other read/write, every session.
    read_block(ser, _MANDATORY_PROBE_ADDR)
    return model


def read_block(ser: "serial.Serial", addr: int) -> bytes:
    cmd = bytes([_READ_CMD, addr >> 8, addr & 0xFF, _BLOCK_LEN])
    ser.write(cmd)
    ser.flush()
    _expect(ser, cmd, f"read echo @ {addr:#06x}")

    header = _read_exact(ser, 4, f"reply header @ {addr:#06x}")
    if header[0] != _WRITE_CMD or header[1:4] != cmd[1:4]:
        raise IOError(f"Malformed read reply header @ {addr:#06x}: {header!r}")
    data = _read_exact(ser, _BLOCK_LEN, f"data @ {addr:#06x}")
    checksum = _read_exact(ser, 1, f"checksum @ {addr:#06x}")[0]

    expected = (sum(header[1:4]) + sum(data)) & 0xFF
    if checksum != expected:
        raise IOError(f"Checksum mismatch @ {addr:#06x}: expected {expected:#04x}, got {checksum:#04x}")
    _expect(ser, bytes([_ACK]), f"ack @ {addr:#06x}")
    return data


def write_block(ser: "serial.Serial", addr: int, data: bytes) -> None:
    assert len(data) == _BLOCK_LEN
    header = bytes([addr >> 8, addr & 0xFF, _BLOCK_LEN])
    checksum = (sum(header) + sum(data)) & 0xFF
    # MKII write frames carry a fixed trailing 0x06 that read frames don't -- see protocol.md.
    frame = bytes([_WRITE_CMD]) + header + data + bytes([checksum, 0x06])

    ser.write(frame)
    ser.flush()
    _expect(ser, frame, f"write echo @ {addr:#06x}")
    _expect(ser, bytes([_ACK]), f"write ack @ {addr:#06x}")


def end_session(ser: "serial.Serial") -> None:
    ser.write(_END_CMD)
    ser.flush()
    _expect(ser, _END_CMD + bytes([_ACK]), "END echo+ack")
    _expect(ser, bytes([_ACK]), "final ack")


def read_full_image(ser: "serial.Serial") -> bytearray:
    """Read 0x0010-0x3ff0 from a real radio -- use this to back up a radio before writing to it."""
    image = bytearray()
    addr = 0x0010
    while addr <= 0x3ff0:
        image += read_block(ser, addr)
        addr += _BLOCK_LEN
    return image


def write_full_image(ser: "serial.Serial", image: bytearray) -> None:
    addr = _WRITE_START
    while addr <= _WRITE_END:
        offset = addr - FACTORY_IMAGE_BASE
        write_block(ser, addr, bytes(image[offset:offset + _BLOCK_LEN]))
        addr += _BLOCK_LEN


def _print_override_summary(overrides: dict) -> None:
    print(f"Channel 0 overrides ({len(overrides)} fields):")
    print(f"  frequency = {CHANNEL_FREQUENCY_HZ / 1_000_000:.5f} MHz, name = {CHANNEL_NAME!r}, "
          f"step = {CHANNEL_STEP}, tx_power = {CHANNEL_TX_POWER}, "
          f"encode = {CHANNEL_ENCODE_TYPE}, decode = {CHANNEL_DECODE_TYPE}")
    print("  raw bytes being patched onto the factory image:")
    for addr in sorted(overrides):
        print(f"    {addr:#06x}: {overrides[addr].hex(' ')}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", required=True, help="Serial port, e.g. COM3 or /dev/ttyUSB0")
    parser.add_argument(
        "--write", action="store_true",
        help="Actually write to the radio. Without this flag, connects, identifies the radio, "
             "and shows what WOULD be written, then exits -- nothing is sent.",
    )
    parser.add_argument(
        "--backup", metavar="PATH",
        help="Read the radio's current full image (0x0010-0x3ff0) and save it to PATH before "
             "writing. Required with --write unless --skip-backup is passed.",
    )
    parser.add_argument(
        "--skip-backup", action="store_true",
        help="Allow --write without --backup. Only the radio's own existing data is at risk -- "
             "use this if you already have a backup, or the radio has nothing worth keeping.",
    )
    parser.add_argument(
        "--force", action="store_true",
        help="Write even if the radio's ID reply doesn't match this radio (DJ-138). Only for "
             "someone who has independently checked this script's offsets against their own unit.",
    )
    args = parser.parse_args()

    if args.write and not args.backup and not args.skip_backup:
        parser.error("--write erases every existing channel/setting on the radio. Pass --backup "
                      "PATH to save a copy first, or --skip-backup to proceed without one.")

    image = build_factory_image()
    overrides = build_channel0_overrides()
    apply_overrides(image, overrides)

    with serial.Serial(
        port=args.port, baudrate=_SERIAL_BAUD, timeout=_SERIAL_TIMEOUT,
        bytesize=serial.EIGHTBITS, parity=serial.PARITY_NONE, stopbits=serial.STOPBITS_ONE,
    ) as ser:
        ser.reset_input_buffer()
        ser.reset_output_buffer()

        model = handshake(ser)
        print(f"Connected: model reply = {model!r}")
        if _EXPECTED_MODEL not in model:
            message = (
                f"model reply {model!r} doesn't contain {_EXPECTED_MODEL!r} (DR-138 MKII). "
                "This script's offsets/frame shapes are NOT verified for other Alinco models -- "
                "see protocol.md before continuing."
            )
            if args.write and not args.force:
                parser.error(message + " Pass --force to write anyway, at your own risk.")
            print(f"WARNING: {message}", file=sys.stderr)

        if not args.write:
            _print_override_summary(overrides)
            print(f"\nDry run (no --write): would write {len(image)} bytes total. "
                  "Re-run with --write to actually program the radio.")
            return

        if args.backup:
            print(f"Reading current image before writing, saving to {args.backup} ...")
            backup_image = read_full_image(ser)
            with open(args.backup, "wb") as f:
                f.write(backup_image)
            print(f"Backup saved: {len(backup_image)} bytes.")

        _print_override_summary(overrides)
        print("\nWriting factory-default image with the overrides above applied...")
        write_full_image(ser, image)
        end_session(ser)
        print("Done. Power-cycle the radio for the write to take effect.")


if __name__ == "__main__":
    main()
