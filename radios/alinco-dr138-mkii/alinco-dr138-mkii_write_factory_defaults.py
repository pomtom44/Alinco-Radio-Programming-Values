def _encode_frequency(freq_hz: int) -> bytes:
    """protocol.md `+0x00`-`+0x03`: byte0 leading digit raw, bytes1-3 BCD pairs, units of 100Hz."""
    units = round(freq_hz / 100)
    s = f"{units:07d}"
    if len(s) != 7 or units < 0:
        raise ValueError(f"{freq_hz} Hz is out of the encodable range")

    def bcd(n: int) -> int:
        tens, ones = divmod(n, 10)
        return (tens << 4) | ones

    return bytes([int(s[0]), bcd(int(s[1:3])), bcd(int(s[3:5])), bcd(int(s[5:7]))])


def _encode_name(name: str) -> bytes:
    """protocol.md `+0x13`-`+0x19`: 7 ASCII bytes, space-padded."""
    return name[:7].upper().ljust(7).encode("ascii", errors="replace")


def build_channel0_overrides() -> dict:
    """Turn the EDITABLE FIELDS above into {offset: byte(s)} patches onto the factory image.

    Offsets are absolute (channel 0 starts at 0x2000, per protocol.md). Only offsets protocol.md
    marks "confirmed" are touched here -- copy this function's shape to add more fields.
    """
    if CHANNEL_ENCODE_TYPE not in _SIGNALING_TYPE_ENCODE:
        raise ValueError(f"CHANNEL_ENCODE_TYPE must be one of {list(_SIGNALING_TYPE_ENCODE)}")
    if CHANNEL_DECODE_TYPE not in _SIGNALING_TYPE_DECODE:
        raise ValueError(f"CHANNEL_DECODE_TYPE must be one of {list(_SIGNALING_TYPE_DECODE)}")
    if CHANNEL_STEP not in _STEP_VALUES:
        raise ValueError(f"CHANNEL_STEP must be one of {list(_STEP_VALUES)}")
    if CHANNEL_TX_POWER not in _TX_POWER_VALUES:
        raise ValueError(f"CHANNEL_TX_POWER must be one of {list(_TX_POWER_VALUES)}")
    if CHANNEL_CTCSS_ENCODE_HZ not in _CTCSS_TABLE:
        raise ValueError(f"CHANNEL_CTCSS_ENCODE_HZ must be one of {list(_CTCSS_TABLE)}")
    if CHANNEL_CTCSS_DECODE_HZ not in _CTCSS_TABLE:
        raise ValueError(f"CHANNEL_CTCSS_DECODE_HZ must be one of {list(_CTCSS_TABLE)}")

    ch0 = 0x2000  # protocol.md: channel N = 0x2000 + N*0x20; this script only ever targets ch0
    overrides = {}
    overrides[ch0 + 0x00] = _encode_frequency(CHANNEL_FREQUENCY_HZ)  # +0x00-0x03
    overrides[ch0 + 0x08] = bytes([_STEP_VALUES[CHANNEL_STEP]])  # +0x08

    # +0x09: bits2-3 Channel Spacing (left at factory 25KHz, bits0/1/4/5 left at factory 0)
    # +0x0a: bits2-3 TX Power, bit0 Duplex direction (left at factory: TX below RX)
    overrides[ch0 + 0x0a] = bytes([_TX_POWER_VALUES[CHANNEL_TX_POWER]])  # +0x0a

    # +0x0b: bits0-1 Encode Type, bits2-3 Decode Type, bits4-7 DTMF slot (left at factory 0)
    signaling_byte = _SIGNALING_TYPE_ENCODE[CHANNEL_ENCODE_TYPE] | _SIGNALING_TYPE_DECODE[CHANNEL_DECODE_TYPE]
    overrides[ch0 + 0x0b] = bytes([signaling_byte])  # +0x0b

    overrides[ch0 + 0x0c] = bytes([_CTCSS_TABLE[CHANNEL_CTCSS_ENCODE_HZ]])  # +0x0c
    overrides[ch0 + 0x0d] = bytes([_CTCSS_TABLE[CHANNEL_CTCSS_DECODE_HZ]])  # +0x0d
    overrides[ch0 + 0x13] = _encode_name(CHANNEL_NAME)  # +0x13-0x19
    return overrides


